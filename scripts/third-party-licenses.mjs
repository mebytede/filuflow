#!/usr/bin/env node
// Lists the licenses of all runtime npm dependencies of filuflow (direct and transitive) as Markdown.
// Source: package-lock.json (packages not marked "dev"); the license field is read from the installed package.json in
// node_modules when present, otherwise from the lock file.
//
// Usage:
//   node scripts/third-party-licenses.mjs           print the Markdown to stdout
//   node scripts/third-party-licenses.mjs --write   replace the generated block in THIRD_PARTY_NOTICES.md
//   node scripts/third-party-licenses.mjs --check   exit 1 if THIRD_PARTY_NOTICES.md is out of date
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const START = '<!-- third-party-licenses:start -->';
const END = '<!-- third-party-licenses:end -->';

function licenseOf(meta) {
  const value = meta.license ?? meta.licenses;
  if (typeof value === 'string') return value;
  if (Array.isArray(value)) return value.map((l) => (typeof l === 'string' ? l : l.type)).join(' OR ');
  if (value && typeof value === 'object' && typeof value.type === 'string') return value.type;
  return 'UNKNOWN';
}

function repositoryOf(meta) {
  const repo = typeof meta.repository === 'string' ? meta.repository : meta.repository?.url;
  if (!repo) return '';
  return repo
    .replace(/^git\+/, '')
    .replace(/^git:\/\//, 'https://')
    .replace(/^ssh:\/\/git@/, 'https://')
    .replace(/^github:/, 'https://github.com/')
    .replace(/^([\w-]+\/[\w.-]+)$/, 'https://github.com/$1')
    .replace(/\.git$/, '');
}

function collect() {
  const lock = JSON.parse(readFileSync(join(root, 'package-lock.json'), 'utf8'));
  const rows = [];
  for (const [path, entry] of Object.entries(lock.packages ?? {})) {
    if (!path || entry.dev || entry.link) continue;
    const name = entry.name ?? path.slice(path.lastIndexOf('node_modules/') + 'node_modules/'.length);
    const pkgFile = join(root, path, 'package.json');
    const meta = existsSync(pkgFile) ? JSON.parse(readFileSync(pkgFile, 'utf8')) : entry;
    rows.push({
      name,
      version: meta.version ?? entry.version ?? '',
      license: licenseOf(meta.license || meta.licenses ? meta : entry),
      repository: repositoryOf(meta),
    });
  }
  // The same package can appear in several versions; keep each name@version once
  const unique = new Map(rows.map((r) => [`${r.name}@${r.version}`, r]));
  return [...unique.values()].sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version));
}

function render(rows) {
  const counts = new Map();
  for (const r of rows) counts.set(r.license, (counts.get(r.license) ?? 0) + 1);
  const summary = [...counts.entries()].sort((a, b) => b[1] - a[1] || a[0].localeCompare(b[0]));
  const lines = [
    START,
    '<!-- Generated by scripts/third-party-licenses.mjs --write. Do not edit by hand. -->',
    '',
    `${rows.length} runtime packages (direct and transitive, without dev dependencies).`,
    '',
    '| License | Packages |',
    '|---|---|',
    ...summary.map(([license, n]) => `| ${license} | ${n} |`),
    '',
    '<details>',
    '<summary>All runtime packages</summary>',
    '',
    '| Package | Version | License | Source |',
    '|---|---|---|---|',
    ...rows.map((r) => `| ${r.name} | ${r.version} | ${r.license} | ${r.repository} |`),
    '',
    '</details>',
    END,
  ];
  return lines.join('\n');
}

const block = render(collect());
const mode = process.argv[2];
if (mode === '--write' || mode === '--check') {
  const file = join(root, 'THIRD_PARTY_NOTICES.md');
  const text = readFileSync(file, 'utf8');
  const from = text.indexOf(START);
  const to = text.indexOf(END);
  if (from < 0 || to < from) {
    process.stderr.write(`THIRD_PARTY_NOTICES.md has no ${START} ... ${END} block\n`);
    process.exit(1);
  }
  const next = text.slice(0, from) + block + text.slice(to + END.length);
  if (mode === '--check') {
    if (next !== text) {
      process.stderr.write('THIRD_PARTY_NOTICES.md is out of date: run node scripts/third-party-licenses.mjs --write\n');
      process.exit(1);
    }
  } else {
    writeFileSync(file, next);
  }
} else {
  process.stdout.write(block + '\n');
}
